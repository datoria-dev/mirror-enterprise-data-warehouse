CREATE OR REPLACE PROCEDURE SECURITY_ANALYTICS.SP_LOAD_DIM_HOST_INCREMENTAL()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
    MERGE INTO SECURITY_ANALYTICS.DIM_HOST tgt
    USING (
        SELECT DISTINCT HOST_ID, HOSTNAME, IP_ADDRESS, OS
        FROM DEV_LANDING.SECURITY_ANALYTICS.L_QUALYS_HOSTS
        WHERE LAST_SCAN_DATETIME >= DATEADD('day', -1, CURRENT_DATE())
    ) src
    ON tgt.HOST_ID = src.HOST_ID
    WHEN MATCHED AND (tgt.HOSTNAME <> src.HOSTNAME OR tgt.IP_ADDRESS <> src.IP_ADDRESS)
    THEN UPDATE SET tgt.HOSTNAME = src.HOSTNAME, tgt.IP_ADDRESS = src.IP_ADDRESS
    WHEN NOT MATCHED THEN INSERT (HOST_ID, HOSTNAME, IP_ADDRESS, OS)
    VALUES (src.HOST_ID, src.HOSTNAME, src.IP_ADDRESS, src.OS);

    RETURN 'DIM_HOST loaded successfully';
END;
$$;

CREATE OR REPLACE PROCEDURE SECURITY_ANALYTICS.SP_LOAD_FACT_QUALYS_INCREMENTAL()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
    MERGE INTO SECURITY_ANALYTICS.FACT_QUALYS tgt
    USING (
        SELECT HOST_ID, VULN_ID, SEVERITY, DETECTED_DATE, STATUS
        FROM DEV_LANDING.SECURITY_ANALYTICS.L_QUALYS_VULNERABILITIES
        WHERE DETECTED_DATE >= DATEADD('day', -1, CURRENT_DATE())
    ) src
    ON tgt.HOST_ID = src.HOST_ID AND tgt.VULN_ID = src.VULN_ID
    WHEN MATCHED AND tgt.STATUS <> src.STATUS
    THEN UPDATE SET tgt.STATUS = src.STATUS, tgt.LAST_UPDATED = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (HOST_ID, VULN_ID, SEVERITY, DETECTED_DATE, STATUS)
    VALUES (src.HOST_ID, src.VULN_ID, src.SEVERITY, src.DETECTED_DATE, src.STATUS);

    RETURN 'FACT_QUALYS loaded successfully';
END;
$$;


    KPI_KEY NUMBER AUTOINCREMENT PRIMARY KEY,
    DATE_KEY NUMBER,
    OPCO_ID NUMBER,
    HOST_ID VARCHAR(255),
    CYBER_MATURITY_SCORE FLOAT,
    TOTAL_POLICY_EXCEPTIONS NUMBER,
    OVERDUE_EXCEPTIONS NUMBER,
    VENDOR_RISK_SCORE FLOAT,
    HIGH_RISK_VENDORS NUMBER,

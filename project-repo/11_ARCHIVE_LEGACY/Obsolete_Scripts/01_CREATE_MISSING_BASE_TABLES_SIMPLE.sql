-- Insert 20 sample records
INSERT INTO FACT_QUALYS (DATE_KEY, HOST_ID, VULN_ID, SEVERITY, CVSS_SCORE, CRITICAL_VULNS, HIGH_VULNS, TOTAL_VULNERABILITIES, FIRST_DETECTED_DATE)
SELECT
    TO_NUMBER(TO_CHAR(CURRENT_DATE(), 'YYYYMMDD')),
    'HOST_' || LPAD(SEQ4(), 5, '0'),
    'CVE-2024-' || LPAD(UNIFORM(1000, 9999, RANDOM()), 4, '0'),
    CASE WHEN SEQ4() % 4 = 0 THEN 'CRITICAL'
         WHEN SEQ4() % 4 = 1 THEN 'HIGH'
         WHEN SEQ4() % 4 = 2 THEN 'MEDIUM'
         ELSE 'LOW' END,
    UNIFORM(3, 10, RANDOM()),
    CASE WHEN SEQ4() % 4 = 0 THEN 1 ELSE 0 END,
    CASE WHEN SEQ4() % 4 = 1 THEN 1 ELSE 0 END,
    1,
    DATEADD('day', -UNIFORM(1, 90, RANDOM()), CURRENT_DATE())
FROM TABLE(GENERATOR(ROWCOUNT => 20))
WHERE NOT EXISTS (SELECT 1 FROM FACT_QUALYS LIMIT 1);

SELECT 'FACT_QUALYS: ' || COUNT(*) || ' rows' AS RESULT FROM FACT_QUALYS;


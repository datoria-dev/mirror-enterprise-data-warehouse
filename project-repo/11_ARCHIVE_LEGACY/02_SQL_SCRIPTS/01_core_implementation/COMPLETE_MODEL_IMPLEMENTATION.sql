-- 4.1 Create Data Lineage View
CREATE OR REPLACE VIEW VW_DATA_LINEAGE_MAP AS
WITH lineage AS (
    -- Landing to Transformation
    SELECT
        'LANDING_TO_TRANSFORM' as FLOW_TYPE,
        l.TABLE_NAME as SOURCE_TABLE,
        'DEV_LANDING' as SOURCE_DB,
        t.TABLE_NAME as TARGET_TABLE,
        'DEV_TRANSFORMATION' as TARGET_DB,
        CASE
            WHEN REPLACE(l.TABLE_NAME, 'RAW_', '') = REPLACE(t.TABLE_NAME, 'DIM_', '')
            THEN 'HIGH'
            WHEN CONTAINS(t.TABLE_NAME, REPLACE(l.TABLE_NAME, 'RAW_', ''))
            THEN 'MEDIUM'
            ELSE 'LOW'
        END as CONFIDENCE
    FROM DEV_LANDING.INFORMATION_SCHEMA.TABLES l
    CROSS JOIN DEV_TRANSFORMATION.INFORMATION_SCHEMA.TABLES t
    WHERE l.TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND t.TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND l.TABLE_TYPE = 'BASE TABLE'
    AND t.TABLE_TYPE = 'BASE TABLE'
    AND (
        CONTAINS(t.TABLE_NAME, REPLACE(l.TABLE_NAME, 'RAW_', ''))
        OR CONTAINS(t.TABLE_NAME, REPLACE(l.TABLE_NAME, 'STG_', ''))
    )
)
SELECT * FROM lineage
WHERE CONFIDENCE IN ('HIGH', 'MEDIUM')
ORDER BY FLOW_TYPE, CONFIDENCE, SOURCE_TABLE;

-- 4.2 Create Dependency Matrix
CREATE OR REPLACE VIEW VW_TABLE_DEPENDENCY_MATRIX AS
WITH dependencies AS (
    SELECT DISTINCT
        rc.CONSTRAINT_NAME,
        rc.UNIQUE_CONSTRAINT_NAME,
        kcu1.TABLE_NAME as CHILD_TABLE,
        kcu1.COLUMN_NAME as CHILD_COLUMN,
        kcu2.TABLE_NAME as PARENT_TABLE,
        kcu2.COLUMN_NAME as PARENT_COLUMN
    FROM INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS rc
    JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE kcu1
        ON rc.CONSTRAINT_NAME = kcu1.CONSTRAINT_NAME
    JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE kcu2
        ON rc.UNIQUE_CONSTRAINT_NAME = kcu2.CONSTRAINT_NAME
    WHERE kcu1.TABLE_SCHEMA = 'SECURITY_ANALYTICS'
)
SELECT
    CHILD_TABLE,
    PARENT_TABLE,
    CHILD_COLUMN || ' -> ' || PARENT_COLUMN as RELATIONSHIP,
    'FOREIGN_KEY' as RELATIONSHIP_TYPE
FROM dependencies
ORDER BY CHILD_TABLE, PARENT_TABLE;


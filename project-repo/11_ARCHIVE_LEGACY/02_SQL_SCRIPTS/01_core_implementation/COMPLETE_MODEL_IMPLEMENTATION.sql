-- 5.1 Daily Health Check Procedure
CREATE OR REPLACE PROCEDURE SP_DAILY_HEALTH_CHECK()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
    v_message VARCHAR DEFAULT '';
    v_pk_count NUMBER;
    v_fk_count NUMBER;
    v_empty_tables NUMBER;
    v_orphaned_records NUMBER;
BEGIN
    -- Check Primary Keys
    SELECT COUNT(DISTINCT TABLE_NAME) INTO v_pk_count
    FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND CONSTRAINT_TYPE = 'PRIMARY KEY';

    -- Check Foreign Keys
    SELECT COUNT(DISTINCT TABLE_NAME) INTO v_fk_count
    FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND CONSTRAINT_TYPE = 'FOREIGN KEY';

    -- Check Empty Tables
    SELECT COUNT(*) INTO v_empty_tables
    FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND TABLE_TYPE = 'BASE TABLE'
    AND ROW_COUNT = 0;

    -- Build message
    v_message := 'HEALTH CHECK RESULTS: ' ||
                 'PKs=' || v_pk_count ||
                 ', FKs=' || v_fk_count ||
                 ', Empty Tables=' || v_empty_tables;

    -- Log results
    INSERT INTO ITSECKPI_BACKUP.IMPLEMENTATION_LOG
    (PHASE, OBJECT_TYPE, OBJECT_NAME, ACTION_TAKEN, STATUS)
    VALUES ('HEALTH_CHECK', 'SYSTEM', 'ALL', v_message, 'COMPLETED');

    RETURN v_message;
END;
$$;

-- 5.2 Data Quality Alert Procedure
CREATE OR REPLACE PROCEDURE SP_DATA_QUALITY_ALERTS()
RETURNS TABLE (ALERT_TYPE VARCHAR, TABLE_NAME VARCHAR, ISSUE VARCHAR, SEVERITY VARCHAR)
LANGUAGE SQL
AS
$$
DECLARE
    res RESULTSET;
BEGIN
    res := (
        SELECT
            'EMPTY_FACT' as ALERT_TYPE,
            TABLE_NAME,
            'Fact table has no data' as ISSUE,
            'HIGH' as SEVERITY
        FROM INFORMATION_SCHEMA.TABLES
        WHERE TABLE_SCHEMA = 'SECURITY_ANALYTICS'
        AND TABLE_TYPE = 'BASE TABLE'
        AND TABLE_NAME LIKE 'FACT_%'
        AND ROW_COUNT = 0

        UNION ALL

        SELECT
            'MISSING_PK' as ALERT_TYPE,
            t.TABLE_NAME,
            'Dimension table without primary key' as ISSUE,
            'CRITICAL' as SEVERITY
        FROM INFORMATION_SCHEMA.TABLES t
        WHERE t.TABLE_SCHEMA = 'SECURITY_ANALYTICS'
        AND t.TABLE_TYPE = 'BASE TABLE'
        AND t.TABLE_NAME LIKE 'DIM_%'
        AND NOT EXISTS (
            SELECT 1
            FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
            WHERE tc.TABLE_NAME = t.TABLE_NAME
            AND tc.TABLE_SCHEMA = t.TABLE_SCHEMA
            AND tc.CONSTRAINT_TYPE = 'PRIMARY KEY'
        )

        UNION ALL

        SELECT
            'LARGE_TABLE' as ALERT_TYPE,
            TABLE_NAME,
            'Table exceeds 1M rows - consider partitioning' as ISSUE,
            'MEDIUM' as SEVERITY
        FROM INFORMATION_SCHEMA.TABLES
        WHERE TABLE_SCHEMA = 'SECURITY_ANALYTICS'
        AND TABLE_TYPE = 'BASE TABLE'
        AND ROW_COUNT > 1000000
    );

    RETURN TABLE(res);
END;
$$;


-- 7.1 Generate Missing Primary Keys
WITH missing_pk AS (
    SELECT
        t.TABLE_NAME,
        (SELECT MIN(COLUMN_NAME)
         FROM INFORMATION_SCHEMA.COLUMNS c
         WHERE c.TABLE_NAME = t.TABLE_NAME
         AND c.TABLE_SCHEMA = t.TABLE_SCHEMA
         AND (c.COLUMN_NAME LIKE '%_ID' OR c.COLUMN_NAME LIKE '%_KEY' OR c.COLUMN_NAME = 'ID')
         AND c.ORDINAL_POSITION = 1) as PK_CANDIDATE
    FROM INFORMATION_SCHEMA.TABLES t
    WHERE t.TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND t.TABLE_TYPE = 'BASE TABLE'
    AND t.TABLE_NAME LIKE 'DIM_%'
    AND NOT EXISTS (
        SELECT 1
        FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
        WHERE tc.TABLE_NAME = t.TABLE_NAME
        AND tc.TABLE_SCHEMA = t.TABLE_SCHEMA
        AND tc.CONSTRAINT_TYPE = 'PRIMARY KEY'
    )
)
SELECT
    'ALTER TABLE ' || TABLE_NAME || ' ADD CONSTRAINT PK_' || TABLE_NAME ||
    ' PRIMARY KEY (' || PK_CANDIDATE || ') RELY;' as DDL_STATEMENT
FROM missing_pk
WHERE PK_CANDIDATE IS NOT NULL;

-- 7.2 Generate Missing Foreign Keys
WITH missing_fk AS (
    SELECT DISTINCT
        f.TABLE_NAME as FACT_TABLE,
        f.COLUMN_NAME as FK_COLUMN,
        CASE
            WHEN f.COLUMN_NAME LIKE '%HOST%' THEN 'DIM_HOST'
            WHEN f.COLUMN_NAME LIKE '%DATE%' THEN 'DIM_DATES'
            WHEN f.COLUMN_NAME LIKE '%DEVICE%' THEN 'DIM_SNOW_DEVICES'
            WHEN f.COLUMN_NAME LIKE '%USER%' THEN 'DIM_ANCON_USERS'
            WHEN f.COLUMN_NAME LIKE '%ENDPOINT%' THEN 'DIM_DEFENDER_ENDPOINTS'
            ELSE NULL
        END as DIM_TABLE,
        CASE
            WHEN f.COLUMN_NAME LIKE '%HOST%' THEN 'HOST_ID'
            WHEN f.COLUMN_NAME LIKE '%DATE%' THEN 'DATE_KEY'
            WHEN f.COLUMN_NAME LIKE '%DEVICE%' THEN 'DEVICE_ID'
            WHEN f.COLUMN_NAME LIKE '%USER%' THEN 'USER_ID'
            WHEN f.COLUMN_NAME LIKE '%ENDPOINT%' THEN 'ENDPOINT_ID'
            ELSE NULL
        END as DIM_COLUMN
    FROM INFORMATION_SCHEMA.COLUMNS f
    WHERE f.TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND f.TABLE_NAME LIKE 'FACT_%'
    AND (f.COLUMN_NAME LIKE '%_ID' OR f.COLUMN_NAME LIKE '%_KEY')
    AND NOT EXISTS (
        SELECT 1
        FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE kcu
        WHERE kcu.TABLE_NAME = f.TABLE_NAME
        AND kcu.COLUMN_NAME = f.COLUMN_NAME
        AND kcu.TABLE_SCHEMA = f.TABLE_SCHEMA
    )
)
SELECT
    'ALTER TABLE ' || FACT_TABLE || ' ADD CONSTRAINT FK_' ||
    REPLACE(FACT_TABLE, 'FACT_', '') || '_' || REPLACE(DIM_TABLE, 'DIM_', '') ||
    ' FOREIGN KEY (' || FK_COLUMN || ') REFERENCES ' ||
    DIM_TABLE || '(' || DIM_COLUMN || ') RELY;' as DDL_STATEMENT
FROM missing_fk
WHERE DIM_TABLE IS NOT NULL
AND DIM_COLUMN IS NOT NULL;


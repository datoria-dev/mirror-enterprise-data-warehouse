-- 2.1 Create Performance Test Procedure
CREATE OR REPLACE PROCEDURE SP_TEST_QUERY_PERFORMANCE()
RETURNS TABLE (TEST_NAME VARCHAR, EXECUTION_TIME_MS NUMBER, ROW_COUNT NUMBER)
LANGUAGE SQL
AS
$$
DECLARE
    start_time TIMESTAMP_NTZ;
    end_time TIMESTAMP_NTZ;
    result_count NUMBER;
    res RESULTSET;
BEGIN
    -- Test 1: Complex JOIN with PKs and FKs
    start_time := CURRENT_TIMESTAMP();

    res := (
        SELECT COUNT(*)
        FROM FACT_REMEDIATION_EVENTS f
        JOIN DIM_HOST h ON f.HOST_ID = h.HOST_ID
        JOIN DIM_DATES d ON f.DATE_KEY = d.DATE_KEY
        WHERE d.YEAR = 2024
    );

    end_time := CURRENT_TIMESTAMP();

    LET c1 CURSOR FOR res;
    OPEN c1;
    FETCH c1 INTO result_count;

    INSERT INTO performance_results
    SELECT
        'Complex JOIN Test' as TEST_NAME,
        DATEDIFF(millisecond, start_time, end_time) as EXECUTION_TIME_MS,
        result_count as ROW_COUNT;

    -- Return results
    res := (SELECT * FROM performance_results);
    RETURN TABLE(res);
END;
$$;

-- 2.2 Create Query Performance Comparison View
CREATE OR REPLACE VIEW VW_QUERY_PERFORMANCE_ANALYSIS AS
WITH query_stats AS (
    SELECT
        QUERY_TEXT,
        QUERY_TYPE,
        DATABASE_NAME,
        SCHEMA_NAME,
        EXECUTION_TIME,
        ROWS_PRODUCED,
        BYTES_SCANNED,
        PARTITIONS_SCANNED,
        COMPILATION_TIME,
        QUEUED_PROVISIONING_TIME + QUEUED_REPAIR_TIME + QUEUED_OVERLOAD_TIME as QUEUE_TIME,
        START_TIME
    FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
    WHERE DATABASE_NAME = 'DEV_TRANSFORMATION'
    AND SCHEMA_NAME = 'SECURITY_ANALYTICS'
    AND START_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP())
    AND EXECUTION_STATUS = 'SUCCESS'
)
SELECT
    DATE(START_TIME) as QUERY_DATE,
    COUNT(*) as TOTAL_QUERIES,
    AVG(EXECUTION_TIME) as AVG_EXECUTION_MS,
    MAX(EXECUTION_TIME) as MAX_EXECUTION_MS,
    MIN(EXECUTION_TIME) as MIN_EXECUTION_MS,
    AVG(BYTES_SCANNED) / 1024 / 1024 as AVG_MB_SCANNED,
    AVG(ROWS_PRODUCED) as AVG_ROWS_PRODUCED
FROM query_stats
GROUP BY DATE(START_TIME)
ORDER BY QUERY_DATE DESC;


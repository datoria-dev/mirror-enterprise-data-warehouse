CREATE OR REPLACE VIEW VW_QUALITY_ALERTS AS
SELECT
    TABLE_NAME,
    OVERALL_SCORE,
    CASE
        WHEN OVERALL_SCORE < 50 THEN 'CRITICAL'
        WHEN OVERALL_SCORE < 75 THEN 'WARNING'
        WHEN OVERALL_SCORE < 90 THEN 'INFO'
        ELSE 'OK'
    END as ALERT_LEVEL,
    CASE
        WHEN OVERALL_SCORE < 50 THEN 'Immediate action required'

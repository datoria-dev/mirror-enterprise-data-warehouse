-- 8. RESUMEN DE PROBLEMAS CRÍTICOS
-- ============================================================

WITH issues_summary AS (
    -- Tablas vacías en Facts
    SELECT
        'EMPTY_FACTS' as ISSUE_TYPE,
        COUNT(*) as ISSUE_COUNT,
        'Critical' as SEVERITY
    FROM DEV_TRANSFORMATION.INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND TABLE_TYPE = 'BASE TABLE'
    AND TABLE_NAME LIKE 'FACT_%'
    AND ROW_COUNT = 0

    UNION ALL

    -- Tablas vacías en Dimensions
    SELECT
        'EMPTY_DIMS' as ISSUE_TYPE,
        COUNT(*) as ISSUE_COUNT,
        'High' as SEVERITY
    FROM DEV_TRANSFORMATION.INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND TABLE_TYPE = 'BASE TABLE'
    AND TABLE_NAME LIKE 'DIM_%'
    AND ROW_COUNT = 0

    UNION ALL

    -- Tablas sin nomenclatura estándar
    SELECT
        'NON_STANDARD_NAMING' as ISSUE_TYPE,
        COUNT(*) as ISSUE_COUNT,
        'Medium' as SEVERITY
    FROM DEV_TRANSFORMATION.INFORMATION_SCHEMA.TABLES
    WHERE TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND TABLE_TYPE = 'BASE TABLE'
    AND TABLE_NAME NOT LIKE 'DIM_%'
    AND TABLE_NAME NOT LIKE 'FACT_%'
    AND TABLE_NAME NOT LIKE 'STG_%'
)
SELECT * FROM issues_summary
ORDER BY
    CASE SEVERITY
        WHEN 'Critical' THEN 1
        WHEN 'High' THEN 2
        WHEN 'Medium' THEN 3
        ELSE 4
    END;

-- 9. GENERAR RECOMENDACIONES DE DDL
-- ============================================================

-- 9.1 Sugerir creación de Primary Keys
SELECT
    'ALTER TABLE ' || TABLE_NAME || ' ADD PRIMARY KEY (' || COLUMN_NAME || ');' as SUGGESTED_DDL,
    'Add PK to ' || TABLE_NAME as DESCRIPTION
FROM (
    SELECT DISTINCT
        t.TABLE_NAME,
        c.COLUMN_NAME
    FROM DEV_TRANSFORMATION.INFORMATION_SCHEMA.TABLES t
    JOIN DEV_TRANSFORMATION.INFORMATION_SCHEMA.COLUMNS c
        ON t.TABLE_NAME = c.TABLE_NAME
        AND t.TABLE_SCHEMA = c.TABLE_SCHEMA
    WHERE t.TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND t.TABLE_TYPE = 'BASE TABLE'
    AND t.TABLE_NAME LIKE 'DIM_%'
    AND (c.COLUMN_NAME = 'ID' OR c.COLUMN_NAME = t.TABLE_NAME || '_ID' OR c.COLUMN_NAME LIKE '%_KEY')
    AND c.ORDINAL_POSITION = 1
)
LIMIT 10;

-- 9.2 Sugerir creación de Foreign Keys
SELECT
    'ALTER TABLE ' || f.TABLE_NAME || ' ADD FOREIGN KEY (' || f.COLUMN_NAME || ') REFERENCES ' ||
    CASE
        WHEN f.COLUMN_NAME LIKE '%USER%' THEN 'DIM_ANCON_USERS(USER_ID)'
        WHEN f.COLUMN_NAME LIKE '%DATE%' THEN 'DIM_DATES(DATE_KEY)'
        WHEN f.COLUMN_NAME LIKE '%HOST%' THEN 'DIM_HOST(HOST_ID)'
        ELSE 'DIM_TABLE(KEY_COLUMN)'
    END || ';' as SUGGESTED_DDL,
    'Add FK from ' || f.TABLE_NAME || '.' || f.COLUMN_NAME as DESCRIPTION
FROM (
    SELECT
        t.TABLE_NAME,
        c.COLUMN_NAME
    FROM DEV_TRANSFORMATION.INFORMATION_SCHEMA.TABLES t
    JOIN DEV_TRANSFORMATION.INFORMATION_SCHEMA.COLUMNS c
        ON t.TABLE_NAME = c.TABLE_NAME
        AND t.TABLE_SCHEMA = c.TABLE_SCHEMA
    WHERE t.TABLE_SCHEMA = 'SECURITY_ANALYTICS'
    AND t.TABLE_TYPE = 'BASE TABLE'
    AND t.TABLE_NAME LIKE 'FACT_%'
    AND (c.COLUMN_NAME LIKE '%_ID' OR c.COLUMN_NAME LIKE '%_KEY')
) f
LIMIT 10;